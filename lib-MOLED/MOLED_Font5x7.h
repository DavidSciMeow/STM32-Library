static inline const uint8_t *MOLED_FindGlyphRows(char Char)
{
  uint16_t i;

  if ((Char >= 'a') && (Char <= 'z'))
  {
    Char = (char)(Char - 'a' + 'A');
  }

  for (i = 0U; i < (uint16_t)(sizeof(MOLED_FontTable) / sizeof(MOLED_FontTable[0])); i++)
  {
    if (MOLED_FontTable[i].ch == Char)
    {
      return MOLED_FontTable[i].rows;
    }
  }

  return MOLED_FontTable[31].rows;
}

